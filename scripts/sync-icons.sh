#!/bin/sh
# Copies Sode's Lucide sprite into src/vendor/lucide as a JS string (esbuild bundles it into the package), with its ISC licence.
# Records the Sode commit, branch and Lucide version in src/vendor/lucide/SOURCE.
# Usage: scripts/sync-icons.sh [path to sode checkout, default ../sode]
set -eu
src="${1:-$(dirname "$0")/../../sode}"
dir="$src/web/vendor/patchbay/icons"
out="$(dirname "$0")/../src/vendor/lucide"
mkdir -p "$out"
cp "$dir/LICENSE" "$out/LICENSE-lucide"
version="$(sed -n 's/.*@license lucide-static \(v[0-9.]*\) - ISC.*/\1/p' "$dir/lucide.svg" | head -n 1)"
[ -n "$version" ] || { echo "no Lucide version in $dir/lucide.svg" >&2; exit 1; }
node -e '
const { readFileSync, writeFileSync } = require("node:fs");
const sprite = readFileSync(process.argv[1], "utf8");
writeFileSync(process.argv[2], "// Generated by scripts/sync-icons.sh from Sode. Do not edit by hand. Licence in ./LICENSE-lucide.\nexport default " + JSON.stringify(sprite) + ";\n");
' "$dir/lucide.svg" "$out/sprite.js"
printf '%s %s lucide-static %s\n' "$(git -C "$src" rev-parse HEAD)" "$(git -C "$src" branch --show-current)" "$version" > "$out/SOURCE"
